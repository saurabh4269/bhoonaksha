window.fillLangMenu = function () {
  const menu = document.getElementById("lang-menu");
  if (!menu || !window.LANGS) return;
  const cur = window.getLang();
  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" })[c];
    });
  }
  menu.innerHTML = window.LANGS.map(function (l) {
    const sel = l.id === cur ? "true" : "false";
    return '<li role="option" data-lang="' + l.id + '" aria-selected="' + sel + '"><span class="lang-native">' + esc(l.native) + '</span><small>' + esc(l.name) + "</small></li>";
  }).join("");
};
window.translateLive = function (text) {
  const lang = window.getLang();
  if (!text || lang === "en") return Promise.resolve(text);
  if (window.__translateOff) return Promise.resolve(text);
  const meta = window.langMeta();
  const target = (meta && meta.code) || "hi-IN";
  return fetch("/api/translate", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ text: String(text), target: target })
  }).then(function (r) {
    if (r.status === 501) { window.__translateOff = true; return text; }
    if (!r.ok) return text;
    return r.json().then(function (j) { return j.text || j.translated_text || text; });
  }).catch(function () { return text; });
};
